"""What anyone (no sign-in) can see about a live business. Nothing private is included."""
import uuid
from datetime import datetime
from decimal import Decimal

from pydantic import BaseModel


class PublicPhotoOut(BaseModel):
    url: str
    thumb_url: str
    width: int
    height: int
    alt_text: str | None


class PublicServiceOut(BaseModel):
    id: uuid.UUID
    name: str
    description: str | None
    duration_minutes: int
    price: Decimal
    deposit: Decimal
    payment_options: list[str]
    kind: str = "main"                  # "add_on" services are shown as extras
    booking_mode: str = "appointment"
    photo: PublicPhotoOut | None = None


class PublicPolicyOut(BaseModel):
    version: int
    summary: list[str]          # plain sentences, generated by code from the confirmed rules
    free_cancel_hours: int
    grace_minutes: int


class PublicRatingOut(BaseModel):
    average: Decimal | None     # None until the business has reviews ("New")
    count: int


class PublicDepositNotice(BaseModel):
      timing: str                         # business_page, booking_start or checkout
      banner: str | None                  # shown on the business page when timing is business_page
      owner_note: str | None


class PublicBusinessOut(BaseModel):
    name: str
    slug: str
    description: str | None
    category: str
    vocabulary: dict
    timezone: str
    currency: str
    address: str | None
    cover: PublicPhotoOut | None
    gallery: list[PublicPhotoOut]
    rating: PublicRatingOut
    services: list[PublicServiceOut]
    policy: PublicPolicyOut
    deposit_notice: PublicDepositNotice


class PublicSlotOut(BaseModel):
    id: uuid.UUID
    starts_at: datetime
    ends_at: datetime
    seats_left: int